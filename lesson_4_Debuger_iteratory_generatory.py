#Ошибки

try:# ключевое слово, которое переводится как «попробовать». Оно открывает блок опасного кода. Python начинает выполнять инструкции внутри этого блока, внимательно следя за тем, не произойдёт ли сбой.
    jhfhffjfjhf
    print(1/0)
except NameError as e:#• блок перехвата («кроме/в случае ошибки...»). Он срабатывает только если внутри try произошла ошибка конкретного типа — NameError (ошибка имени, то есть попытка использовать несуществующую переменную или функцию). Если бы возникла другая ошибка (например, деление на ноль ZeroDivisionError), этот блок бы её проигнорировал, и программа всё равно бы сломалась. создание псевдонима (переменной) для самой ошибки. В переменную e (сокращение от error или exception) записывается объект ошибки со всеми её техническими подробностями и текстом сообщения.
    print("fixed:", e)

#1. Python заходит в блок try и пытается найти переменную jhfhffjfjhf.
# 2. Переменной нет, поэтому Python генерирует исключение NameError: name 'jhfhffjfjhf' is not defined.
# 3. Вместо того чтобы аварийно завершить работу и показать пользователю пугающий красный текст с трассировкой ошибки, интерпретатор видит блок except NameError.
# 4. Программа перепрыгивает в этот блок, сохраняет текст 'name 'jhfhffjfjhf' is not defined' в переменную e и выполняет print.




try:
    #jhfhffjfjhf
    print(1/0)#деление на ноль Теперь добавим эксепт для деления на ноль
except NameError as e:#• блок перехвата («кроме/в случае ошибки...»). Он срабатывает только если внутри try произошла ошибка конкретного типа — NameError (ошибка имени, то есть попытка использовать несуществующую переменную или функцию). Если бы возникла другая ошибка (например, деление на ноль ZeroDivisionError), этот блок бы её проигнорировал, и программа всё равно бы сломалась. создание псевдонима (переменной) для самой ошибки. В переменную e (сокращение от error или exception) записывается объект ошибки со всеми её техническими подробностями и текстом сообщения.
    print("fixed:", e)

except ZeroDivisionError as e:#имя ошибки копируем из консоли с ошибкой - НЕ произвольніе имена
    print("fixed:", e)#fixed: division by zero

except Exception as e:#Exception главная ошибка, найдет любую ошибку
    print("fixed Error", e)

print("JJJ")

