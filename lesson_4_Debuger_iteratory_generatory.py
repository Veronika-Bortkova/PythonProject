#Генераторы - Генератор в Python — это специальный вид итератора (функция или выражение), который поочерёдно выдаёт элементы по мере запроса, не вычисляя и не сохраняя всю последовательность в оперативной памяти целиком.
#Ленивые вычисления (Lazy evaluation): следующее значение вычисляется только в тот момент, когда к генератору обращаются (например, через функцию next() или в цикле for).
