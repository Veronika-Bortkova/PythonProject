#Чтобы любой объект в Python можно было засунуть в цикл for или передавать в функцию next(), он обязан соблюдать протокол итератора — то есть иметь внутри два магических метода:

#Метод 1: def __iter__(self): return self
#• Когда вызывается: автоматически 1 раз в самом начале цикла for x in r: (или при ручном вызове iter(r)).
#• Зачем нужен: цикл for перед стартом спрашивает у объекта: «Дай мне того, кто будет выдавать элементы по одному».
#• Что делает return self: объект отвечает: «Я сам и есть итератор, бери элементы прямо из меня».

#Метод 2: def __next__(self):

#• Когда вызывается: автоматически на каждом витке цикла for (или при ручном вызове next(r)).
#• Как работает внутри по шагам:
#	1. if self.__counter < self.__length: — проверяет, не дошли ли мы до конца (0 < 3 -> Да).
#	2. res = self.__counter — сохраняет текущее число (0) во временную переменную res, чтобы вернуть именно его.
#	3. self.__counter += 1 — увеличивает внутренний счётчик на единицу (1), готовя его для следующего вызова __next__. (Если бы мы сначала увеличили счётчик, а потом сделали return, мы бы пропустили ноль).
#	4. return res — отдаёт сохранённое число 0 наружу.
#	5. raise StopIteration — как только условие self.__counter < self.__length станет ложным (3 < 3 -> Нет), метод принудительно выбрасывает исключение StopIteration. Это официальный сигнал для цикла for, что элементы закончились и пора остановиться.

