# 	• range(5) выдаст: 0, 1, 2, 3, 4 (всего 5 чисел, верхняя граница не включается).
# 2. range(start, stop) — генерирует числа от start до stop - 1.
# 	• range(2, 6) выдаст: 2, 3, 4, 5.
# 3. range(start, stop, step) — генерирует числа от start до stop - 1 с шагом step.
# 	• range(1, 10, 2) выдаст только нечётные числа: 1, 3, 5, 7, 9.
# 	• С помощью отрицательного шага можно идти в обратном порядке: range(5, 0, -1) выдаст: 5, 4, 3, 2, 1.
