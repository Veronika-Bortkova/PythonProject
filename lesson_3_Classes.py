#реализация массивовов как в джаваскриптее с пушами и др методами с помощьбю перегрузок и функций

class Array:
    def __init__(self, *args):
        self.__arr = [*args]

    def __str__(self) -> str:
        return str(self.__arr)

    def __len__(self):
        return len(self.__arr)

    def __setitem__(self, key, value):
        self.__arr[key] = value# в данном случае ключ это индекс

    def __getitem__(self, key):
        return self.__arr[key]

    def __delitem__(self, key):
        del self.__arr[key]

    def push (self, item):
        self.__arr.append(item)

    def map (self, cb):
        return Array(*[cb(item) for item in self.__arr])

    def filter (self, cb):
        return Array(*[item for item in self.__arr if cb(item)])



arr = Array(1,2,3,4,5)
print(arr)#[1, 2, 3, 4, 5]
print(len(arr))#5
arr.push(7)
print(arr)#[1, 2, 3, 4, 5, 7]
print(arr[0])#1
arr[2] = 77
print(arr)#[1, 2, 77, 4, 5, 7]
del arr[1]
print(arr)#[1, 77, 4, 5, 7]
for x in arr:
    print(x)# выведет все значения по очереди

arr2 = arr.map(lambda x: x*2)
print(arr2)#[2, 154, 8, 10, 14]

arr3 = arr.filter(lambda x: x>50)
print(arr3)#[77]

